-- OLTPSemi_55.OLTP55_Schema.[Container] -> Kafka topic oltp55_schema_container
-- -> ClickHouse fdp.oltp55_schema_container (clickhouse/init/004_*.sql).
--
-- Credentials live in the source table DDL below. Submit with:
--   docker exec -it fdp-engine-flink-jobmanager /opt/flink/bin/sql-client.sh \
--     -f /opt/flink/usrlib/sql/container_to_clickhouse.sql
--
-- The source needs CDC enabled on the table (mssql/init/003_enable_cdc.sql) and
-- the ClickHouse DDL applied:
--   Get-Content -Raw clickhouse/init/004_oltp55_schema_container.sql | docker exec -i fdp-engine-clickhouse clickhouse-client --multiquery
--
-- No PRIMARY KEY is declared on the source on purpose. With a key Flink plans the
-- changelog as upsert, and the sink format has to be able to carry it; without one
-- the CDC reader still emits update and delete events, which is why the sink uses
-- debezium-json. 'scan.incremental.snapshot.chunk.key-column' replaces the key for
-- the initial snapshot chunks.
--
-- Column list generated from the table DDL with mssql/tools/introspect_container.py
-- type mapping (nvarchar->VARCHAR, char->CHAR, int->INT, float->DOUBLE, bit->BOOLEAN,
-- datetime->TIMESTAMP(3)). Regenerate it if the table changes.
-- Generated by mssql/tools/introspect_container.py. Contains the SQL Server
-- password in clear text; it is gitignored, do not commit it.
-- Submit with:
--   docker exec -it fdp-engine-flink-jobmanager /opt/flink/bin/sql-client.sh \
--     -f /opt/flink/usrlib/sql/generated/container_to_clickhouse.sql
-- Create the ClickHouse table, Kafka engine table and materialized view first
-- (generated in clickhouse/init), otherwise the sink fails.
SET 'execution.checkpointing.interval' = '30 s';
SET 'execution.checkpointing.tolerable-failed-checkpoints' = '100';
