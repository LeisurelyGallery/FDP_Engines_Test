-- The TaskManager has taskmanager.numberOfTaskSlots: 2 and the consolidate_users
-- job already holds one, so this job runs single threaded. Raise the slot count in
-- Docker-compose.yml to run both in parallel.
SET 'parallelism.default' = '1';

